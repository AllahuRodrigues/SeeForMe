"""Write results/campus/CAMPUS_RESULTS.md from the CampusBench result files."""
import json, datetime
from campus_common import RESULTS_C
from _common import MODELS

S = json.loads((RESULTS_C / "summary_test.json").read_text())
K = json.loads((RESULTS_C / "summary_by_kind_test.json").read_text())
tune = json.loads((RESULTS_C / "pcacs_tuning.json").read_text()) if (RESULTS_C / "pcacs_tuning.json").exists() else None
sched = json.loads((MODELS / "scheduler_report.json").read_text()) if (MODELS / "scheduler_report.json").exists() else None
f = lambda x, n=2: ("n/a" if x != x else f"{x:.{n}f}")

L = [f"# CampusBench results ({datetime.date.today()})", "",
     "Generated by `scripts/write_campus_results.py`. Reproduce with `make campus-all`.", "",
     "## 1. Benchmark",
     "* 11 scene types (courtyard, hallway, stairs, doors, crossing, finding, crowd, temporary hazard, poor capture, negative, changing); "
     "66 train / 33 val / 66 test scenarios of 30 s, 10 detections/s, 3 detector+depth noise seeds per test scenario.",
     "* Objects live in metres relative to a walking user; bounding boxes come from a pinhole camera; a noisy detector and a noisy metric depth sensor produce the observations.",
     "* Ground truth per event: should_speak, severity, earliest useful / ideal / latest safe time, path intersection, minimum information slots, ideal cue (see `docs/campus_annotation.md`).",
     "* Communication score = Σ severity × timeliness of the first in-window cue − 0.3 per off-window or repeated cue − 0.5 × severity per late/missed event − 0.15 per second of speech. Regret = oracle score − policy score.",
     "", "## 2. Main result (held-out test split)", "",
     "| policy | action-weighted recall | late critical rate | mean lead (s) | cue precision | audio occupancy | cues/min | haptics/min | silence precision | critical blocking | min-message ratio | regret |",
     "|---|---|---|---|---|---|---|---|---|---|---|---|"]
order = [p for p in ["oracle", "confidence_threshold", "confidence_cooldown", "cacs", "pcacs", "pcacs_learned:il", "pcacs_learned:rl"] if p in S]
for p in order:
    a = S[p]
    L.append(f"| {p} | {f(a['action_weighted_recall'],3)} ± {f(a['recall_sd'])} | {f(a['late_critical_rate'])} | {f(a['mean_lead_s'])} | {f(a['cue_precision'],3)} | "
             f"{f(a['audio_occupancy'])} | {f(a['cues_per_min'],1)} | {f(a['haptics_per_min'],1)} | {f(a['silence_precision'])} | {f(a['critical_blocking_rate'])} | {f(a['min_message_ratio'])} | {f(a['regret'])} |")
L += ["", "### 2.1 Action-weighted recall by scene type", "", "| scene | " + " | ".join(order) + " |", "|---|" + "---|" * len(order)]
for k, d in K.items():
    L.append(f"| {k} | " + " | ".join(f(d.get(p, {}).get('action_weighted_recall', float('nan'))) for p in order) + " |")
L += ["", "### 2.2 Late critical rate by scene type (non-sudden events)", "", "| scene | " + " | ".join(order) + " |", "|---|" + "---|" * len(order)]
for k, d in K.items():
    L.append(f"| {k} | " + " | ".join(f(d.get(p, {}).get('late_critical_rate_nonsudden', float('nan'))) for p in order) + " |")
abl = [p for p in S if p.startswith("pcacs-")]
if abl:
    L += ["", "## 3. P-CACS ablations", "", "| variant | action-weighted recall | late critical rate | cue precision | audio occupancy | cues/min | haptics/min | regret |", "|---|---|---|---|---|---|---|---|"]
    for p in ["pcacs"] + abl:
        a = S[p]
        L.append(f"| {p} | {f(a['action_weighted_recall'],3)} | {f(a['late_critical_rate'])} | {f(a['cue_precision'],3)} | {f(a['audio_occupancy'])} | {f(a['cues_per_min'],1)} | {f(a['haptics_per_min'],1)} | {f(a['regret'])} |")
if tune:
    b = tune["best_config"]; w = b["weights"]
    L += ["", "## 4. Tuned linear P-CACS", "",
          f"Random search, {len(tune['history'])-1} trials on the train split, objective = communication score. Best: "
          + ", ".join(f"{k}={v:.2f}" for k, v in w.items()) + f", threshold_speak={b['threshold_speak']:.2f}, threshold_interrupt={b['threshold_interrupt']:.2f}, "
          f"budget_refill={b['budget_refill']:.2f} s/s, urgent_bypass={b['urgent_bypass']:.2f}, ttc_horizon={b['ttc_horizon']:.1f} s. "
          f"Train score {tune['best']['score']:.3f} (regret {tune['best']['regret']:.3f})."]
if sched:
    il, rl = sched["il"], sched["rl"]
    L += ["", "## 5. Learned scheduler (GRU over the last 8 decision steps, 29 signals per step)", "",
          "| stage | val score | regret | action-weighted recall | cue precision | audio occupancy | late critical rate |", "|---|---|---|---|---|---|---|"]
    for h in il["history"]:
        L.append(f"| DAgger iter {h['iter']} (n={h['n']}, thr={h['threshold']}) | {f(h['score'],3)} | {f(h['regret'],3)} | {f(h['action_weighted_recall'],3)} | {f(h['cue_precision'],3)} | {f(h['audio_occupancy'])} | {f(h['late_critical_rate'])} |")
    for h in rl["history"]:
        L.append(f"| REINFORCE epoch {h['epoch']} | {f(h['score'],3)} | {f(h['regret'],3)} | {f(h['action_weighted_recall'],3)} | {f(h['cue_precision'],3)} | {f(h['audio_occupancy'])} | {f(h['late_critical_rate'])} |")
L += ["", "Figures: `results/campus/figures/campus_main.png`, `campus_tradeoff.png`, `campus_by_kind.png`, `campus_ablation.png`, `campus_scheduler_training.png`."]
(RESULTS_C / "CAMPUS_RESULTS.md").write_text("\n".join(L) + "\n")
print("->", RESULTS_C / "CAMPUS_RESULTS.md")
